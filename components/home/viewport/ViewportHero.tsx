'use client';
import Image from 'next/image';
import { useTranslations } from 'next-intl';
import { useEffect, useRef, useState, type CSSProperties } from 'react';
import { usePerfStore } from '@/lib/perf';
import { CoverUpload } from '../cover/CoverUpload';
import { titleEn, titleZh } from '@/components/site/fonts';
import { GameHUD } from './GameHUD';
import { PrintPins, PrintStatus } from './PrintHUD';

/**
 * Homepage hero as a 3D software viewport: perspective grid floor, axis gizmo,
 * an inspector panel and an asset outliner. The centre model sits on a turntable,
 * tilts with the pointer, and is generated by the scan line each time it changes
 * (point grid -> clay -> PBR). Display modes: wireframe / clay / PBR.
 * Images are transparent renders; swap for GLB + three.js later for true orbit.
 */
type Model = {
  id: string;
  src: string;
  faces: number;
  verts: number;
  maps: number;
  /** untextured sculpt shown during the clay pass; omit to go wire -> final directly */
  clay?: string;
  /** triangulated wireframe render aligned to src */
  wire?: string;
  wide?: boolean;
};
const MODELS: readonly Model[] = [
  {
    id: 'qilin',
    src: '/community/qilin-pbr-v2.webp',
    wire: '/community/qilin-wire-v2.webp',
    wide: true,
    faces: 128400,
    verts: 64215,
    maps: 4,
  },
  { id: 'corgi', src: '/core/corgi-model-cut.webp', faces: 12400, verts: 6218, maps: 4 },
  { id: 'knight', src: '/community/knight.webp', faces: 18900, verts: 9504, maps: 4 },
  { id: 'robot', src: '/core/robot-model-cut.webp', faces: 9800, verts: 4936, maps: 4 },
  { id: 'chest', src: '/community/chest.webp', faces: 7200, verts: 3655, maps: 4 },
  { id: 'sneaker', src: '/community/sneaker.webp', faces: 10600, verts: 5321, maps: 4 },
  { id: 'ding', src: '/community/ding.webp', faces: 15300, verts: 7702, maps: 4 },
];
type Mode = 'wire' | 'clay' | 'pbr';
const GEN_MS = 3600;
const HOLD_MS = 4200;
const SCENE_MS = [GEN_MS + HOLD_MS, 5000, 5000];
const SCENES = [
  { id: 'model', img: null, px: 0, py: 0, ar: 1 },
  { id: 'print', img: '/community/qilin-print-v4.webp', px: 0.5, py: 0.5, ar: 16 / 9 },
  { id: 'game', img: '/community/qilin-game-v2.webp', px: 0.55, py: 0, ar: 1.5 },
] as const;

/** Vertical band the model and scene subjects occupy, between the title and the upload card. */
const STAGE =
  'top-[calc(var(--header-h)+150px)] md:top-[calc(var(--header-h)+170px)] md:bottom-[27%]';

function Grad({
  children,
  className = 'block',
}: {
  children: React.ReactNode;
  className?: string;
}) {
  return (
    <span
      className={`block bg-[linear-gradient(100deg,#9cc8ff,#6FA8FF_50%,#c7d7ff)] bg-clip-text text-transparent ${className}`}
    >
      {children}
    </span>
  );
}

const gridMask =
  '[mask-image:var(--m)] [mask-position:bottom] [mask-repeat:no-repeat] [mask-size:contain] [background:radial-gradient(circle,rgba(225,240,255,1)_1.2px,transparent_1.9px)_0_0/12px_12px,repeating-linear-gradient(0deg,rgba(120,180,255,0.8)_0_1px,transparent_1px_12px),repeating-linear-gradient(90deg,rgba(120,180,255,0.8)_0_1px,transparent_1px_12px)]';

export function ViewportHero({ locale }: { locale: string }) {
  const t = useTranslations('home.viewport');
  const reduced = usePerfStore((s) => s.reducedMotion);
  const [idx] = useState(0);
  const [mode] = useState<Mode>('pbr');
  const [gen, setGen] = useState(reduced ? 1 : 0); // 0..1 generation progress
  const [auto] = useState(true);
  const [tilt, setTilt] = useState({ x: 0, y: 0 });
  const stage = useRef<HTMLDivElement>(null);
  const brush = locale === 'zh' ? titleZh : titleEn;
  const m = MODELS[idx];

  // One timeline: scene 0 generates the model and holds, then the same model is
  // shown 3D-printed (scene 1) and fighting in a game (scene 2), then it loops.
  const [scene, setScene] = useState(0);
  const [sceneK, setSceneK] = useState(0);
  const sceneStart = useRef(0);
  useEffect(() => {
    if (reduced) {
      // eslint-disable-next-line react-hooks/set-state-in-effect -- static finished frame
      setGen(1);
      return;
    }
    let raf = 0;
    sceneStart.current = performance.now();
    if (scene === 0) setGen(0);
    const tick = (now: number) => {
      const el = now - sceneStart.current;
      if (scene === 0) setGen(Math.min(el / GEN_MS, 1));
      const dur = SCENE_MS[scene];
      setSceneK(Math.min(el / dur, 1));
      if (auto && el >= dur) {
        setScene((n) => (n + 1) % SCENE_MS.length);
        return;
      }
      raf = requestAnimationFrame(tick);
    };
    raf = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(raf);
  }, [scene, idx, auto, reduced]);

  const eased = 1 - Math.pow(1 - gen, 2.4);
  const clayCut = Math.min(eased / 0.6, 1); // clay rises first
  const pbrCut = m.wire && !m.clay ? eased : Math.max((eased - 0.45) / 0.55, 0); // then PBR sweeps up
  const showPbr = mode === 'pbr';
  const showClay = mode !== 'wire' && !(m.wire && !m.clay);
  const faces = Math.round(m.faces * clayCut);

  const onMove = (e: React.PointerEvent) => {
    if (reduced || e.pointerType !== 'mouse') return;
    const r = stage.current?.getBoundingClientRect();
    if (!r) return;
    setTilt({
      x: ((e.clientX - r.left) / r.width - 0.5) * 2,
      y: ((e.clientY - r.top) / r.height - 0.5) * 2,
    });
  };

  const modelStyle = {
    '--m': `url(${m.src})`,
    transform: `rotateY(${tilt.x * 14}deg) rotateX(${-tilt.y * 6}deg)`,
  } as CSSProperties;
  const lineY = `${(1 - (gen < 1 ? (pbrCut > 0 ? pbrCut : clayCut) : 1)) * 100}%`;

  return (
    <section
      ref={stage}
      onPointerMove={onMove}
      onPointerLeave={() => setTilt({ x: 0, y: 0 })}
      aria-labelledby="hero-title"
      className="relative h-[100svh] min-h-[700px] overflow-hidden bg-[#05080F] text-white"
    >
      {/* ---------- viewport background ---------- */}
      <div
        aria-hidden
        className="absolute inset-0 [background:radial-gradient(60%_50%_at_50%_58%,rgba(47,107,255,0.22),transparent_70%)]"
      />
      <div
        aria-hidden
        className="absolute inset-x-[-40%] bottom-[-10%] h-[62%] origin-bottom [perspective:700px]"
      >
        <div className="vp-floor absolute inset-0 [transform:rotateX(68deg)] [background:linear-gradient(rgba(111,168,255,0.22)_1px,transparent_1px)_0_0/64px_64px,linear-gradient(90deg,rgba(111,168,255,0.22)_1px,transparent_1px)_0_0/64px_64px] [mask-image:radial-gradient(55%_75%_at_50%_100%,#000,transparent)]" />
      </div>

      {/* ---------- the model on its turntable ---------- */}
      <div
        className={`absolute inset-x-0 bottom-[40%] flex items-end justify-center transition-opacity duration-500 [perspective:1200px] ${STAGE} ${scene === 0 ? '' : 'opacity-0'}`}
      >
        <div
          className={`relative h-full max-w-[92vw] ${m.wide ? 'aspect-[8/5]' : 'aspect-square'}`}
        >
          {/* turntable */}
          <div
            aria-hidden
            className="absolute bottom-[1%] left-1/2 h-[14%] w-[72%] -translate-x-1/2"
          >
            <span className="absolute inset-0 rounded-[50%] border border-[#6FA8FF]/40 bg-[radial-gradient(closest-side,rgba(47,107,255,0.25),transparent)]" />
            <span className="vp-ring absolute inset-[-6%] rounded-[50%] border-2 border-dashed border-[#6FA8FF]/35" />
            <span className="absolute inset-x-[18%] top-[30%] h-[40%] rounded-[50%] bg-black/60 blur-md" />
          </div>
          <div
            className="absolute inset-x-[4%] bottom-[5%] top-0 transition-transform duration-300 ease-out [transform-style:preserve-3d]"
            style={modelStyle}
          >
            {/* wireframe / point grid (always under) */}
            {m.wire ? (
              <div className="absolute inset-0">
                <Image
                  key={`wb-${m.id}`}
                  src={m.src}
                  alt=""
                  fill
                  sizes="(min-width:1024px) 900px, 90vw"
                  className="object-contain object-bottom opacity-40 [filter:grayscale(1)_brightness(0.5)_sepia(1)_hue-rotate(180deg)_saturate(2.2)]"
                />
                <Image
                  key={`w-${m.id}`}
                  src={m.wire}
                  alt=""
                  fill
                  sizes="(min-width:1024px) 900px, 90vw"
                  className="object-contain object-bottom [filter:drop-shadow(0_0_6px_rgba(94,168,255,0.55))]"
                />
              </div>
            ) : (
              <div
                className={`absolute inset-0 ${gridMask} transition-opacity duration-500 ${mode === 'wire' ? 'opacity-100' : 'opacity-70'}`}
              />
            )}
            {/* clay */}
            {showClay && (
              <div
                className="absolute inset-0"
                style={{ clipPath: `inset(${(1 - clayCut) * 100}% 0 0 0)` }}
              >
                <Image
                  key={`c-${m.id}`}
                  src={m.clay ?? m.src}
                  alt=""
                  fill
                  priority
                  sizes="(min-width:1024px) 900px, 90vw"
                  className={`object-contain object-bottom ${m.clay ? '' : '[filter:grayscale(1)_brightness(1.55)_contrast(0.78)]'}`}
                />
                {!m.clay && <div className={`absolute inset-0 ${gridMask} opacity-20`} />}
              </div>
            )}
            {/* PBR */}
            {showPbr && (
              <div
                className="absolute inset-0"
                style={{ clipPath: `inset(${(1 - pbrCut) * 100}% 0 0 0)` }}
              >
                <Image
                  key={`p-${m.id}`}
                  src={m.src}
                  alt={t(`models.${m.id}`)}
                  fill
                  priority
                  sizes="(min-width:1024px) 900px, 90vw"
                  className="object-contain object-bottom"
                />
              </div>
            )}
            {/* mesh mask: triangulated wireframe over the surface while generating */}
            {m.wire && mode !== 'wire' && (
              <Image
                key={`wm-${m.id}`}
                src={m.wire}
                alt=""
                fill
                sizes="(min-width:1024px) 900px, 90vw"
                className={`pointer-events-none object-contain object-bottom mix-blend-screen transition-opacity duration-1000 ${gen < 1 ? 'opacity-60' : 'opacity-0'}`}
              />
            )}
            {gen < 1 && (
              <span
                className="absolute inset-x-[-10%] h-[2px] bg-[#9cc8ff] shadow-[0_0_20px_5px_rgba(94,168,255,0.85)]"
                style={{ top: lineY }}
              >
                {
                  <span className="absolute bottom-2 right-0 hidden whitespace-nowrap font-mono text-[11px] tracking-wider text-[#cfe3ff] [text-shadow:0_0_10px_rgba(94,168,255,0.9)] md:block">
                    {t('generating')} {Math.round(gen * 100)}% · {faces.toLocaleString()}{' '}
                    {t('faces')}
                  </span>
                }
              </span>
            )}
          </div>
        </div>
      </div>

      {/* ---------- scenes 2 & 3: the same model, printed and in a game ----------
          Full-bleed. Each shot is laid out in an object-cover box sized with
          container units, so pins can be placed in % of the image itself. */}
      {SCENES.map(
        (sc, n) =>
          sc.img && (
            <div
              key={`${sc.id}-${scene === n}`}
              aria-hidden={scene !== n}
              className={`absolute inset-0 overflow-hidden transition-opacity duration-500 [container-type:size] ${scene === n ? 'opacity-100' : 'pointer-events-none opacity-0'}`}
            >
              {scene === n && (
                <>
                  <div className="vp-reveal absolute inset-0">
                    <div
                      className="absolute"
                      style={{
                        aspectRatio: sc.ar,
                        width: `max(100cqw, ${sc.ar * 100}cqh)`,
                        left: `calc((100cqw - max(100cqw, ${sc.ar * 100}cqh)) * ${sc.px})`,
                        top: `calc((100cqh - max(100cqw, ${sc.ar * 100}cqh) / ${sc.ar}) * ${sc.py})`,
                      }}
                    >
                      <Image
                        src={sc.img}
                        alt={t(`scenes.${sc.id}.alt`)}
                        fill
                        sizes="100vw"
                        className={`object-cover ${reduced ? '' : 'cover-kenburns'}`}
                      />
                      {sc.id === 'print' && <PrintPins progress={sceneK} reduced={reduced} />}
                    </div>
                  </div>
                  <span className="vp-reveal-line absolute inset-x-0 h-[2px] bg-[#9cc8ff] shadow-[0_0_24px_6px_rgba(94,168,255,0.85)]" />
                  <div className="pointer-events-none absolute inset-0 bg-[linear-gradient(180deg,rgba(5,8,15,0.92)_0%,rgba(5,8,15,0.72)_20%,rgba(5,8,15,0.25)_32%,transparent_42%),linear-gradient(0deg,rgba(5,8,15,0.92)_0%,rgba(5,8,15,0.45)_26%,transparent_45%),radial-gradient(120%_80%_at_50%_50%,transparent_60%,rgba(5,8,15,0.5))]" />
                  {sc.id === 'print' && <PrintStatus progress={sceneK} reduced={reduced} />}
                  {sc.id === 'game' && <GameHUD progress={sceneK} reduced={reduced} />}
                </>
              )}
            </div>
          ),
      )}
      {scene !== 0 && (
        <span className="absolute left-5 top-[calc(var(--header-h)+14px)] z-[3] hidden rounded bg-black/50 px-2 py-1 font-mono text-[11px] text-white/80 backdrop-blur md:left-8 md:inline-block">
          {t(`scenes.${SCENES[scene].id}.tag`)}
        </span>
      )}

      {/* ---------- input photo -> model flow ---------- */}
      {scene === 0 && (
        <div
          aria-hidden
          className="pointer-events-none absolute inset-x-0 top-[calc(var(--header-h)+190px)] hidden xl:block"
        >
          {/* input photo card */}
          <div className="absolute left-[6%] top-[6%] w-[220px] -rotate-[5deg] rounded-xl border border-white/12 bg-[rgba(10,16,30,0.7)] p-2 shadow-[0_20px_60px_rgba(0,0,0,0.5)] backdrop-blur">
            <div className="relative aspect-[16/10] overflow-hidden rounded-lg">
              <Image
                src="/community/qilin-src-v2.webp"
                alt=""
                fill
                sizes="220px"
                className="object-cover"
              />
            </div>
            <p className="mt-2 flex items-center justify-between px-1 font-mono text-[10px] text-white/55">
              <span>{t('io.input')}</span>
              <span className="text-white/80">qilin.jpg</span>
            </p>
          </div>
          {/* flow arrow */}
          <svg
            className="absolute left-[calc(6%+200px)] top-[2%] h-[140px] w-[16vw]"
            viewBox="0 0 200 140"
            preserveAspectRatio="none"
            fill="none"
          >
            <path
              id="flow"
              d="M4 70 C 70 0, 130 0, 196 60"
              stroke="rgba(156,200,255,0.55)"
              strokeWidth="1.4"
              strokeDasharray="4 6"
              vectorEffect="non-scaling-stroke"
            />
            <circle r="3.5" fill="#cfe3ff">
              <animateMotion
                dur="2.4s"
                repeatCount="indefinite"
                path="M4 70 C 70 0, 130 0, 196 60"
              />
            </circle>
          </svg>
        </div>
      )}

      {/* ---------- title ---------- */}
      <div className="pointer-events-none absolute inset-x-0 top-[calc(var(--header-h)+18px)] z-[2] px-5 text-center md:top-[calc(var(--header-h)+28px)]">
        <h1
          id="hero-title"
          className={`${brush.className} text-[clamp(2.2rem,4.4vw,4.2rem)] leading-[1.1] [text-shadow:0_4px_30px_rgba(0,0,0,0.6)] ${locale === 'zh' ? 'tracking-[0.04em]' : 'font-black uppercase'}`}
        >
          {t('titleA')}
          <Grad className="md:inline">{t('titleB')}</Grad>
        </h1>
        <p className="mx-auto mt-3 hidden max-w-[680px] text-[15px] leading-relaxed text-white/65 sm:block">
          {t('subtitle')}
        </p>
      </div>

      {/* ---------- upload ---------- */}
      <div className="absolute inset-x-0 bottom-24 z-10 flex justify-center px-4 md:bottom-8">
        <div className="relative w-full max-w-[860px]">
          <CoverUpload />
        </div>
      </div>
    </section>
  );
}
